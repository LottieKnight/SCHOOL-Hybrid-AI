export function buildGatewayConfig(): GatewayConfig {
  return {
    port: parseInt(process.env.GATEWAY_PORT || '8080'),
    environment: (process.env.NODE_ENV as GatewayConfig['environment']) || 'development',
    ventures: buildServiceRegistry(),
    jwtSecret: process.env.GATEWAY_JWT_SECRET || 'dev-jwt-secret-change-in-production',
    apiKeySecret: process.env.GATEWAY_API_KEY_SECRET || 'dev-api-key-secret-change-in-production',
    defaultRateLimit: { windowMs: 60000, max: 100, scope: 'user' },
    logLevel: 'info',
  };
}